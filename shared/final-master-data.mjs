const masterNorm = v => String(v ?? '').toUpperCase().replace(/[^A-Z0-9]/g,'');
const majorToMinor = v => Math.round(Number(v||0)*100);
export function applyFinalMasterData(state,today='2026-09-12'){
  const vendorFor = code => state.vendors.find(v =>
    [v.code,v.fullReference,v.vendorSerial,v.fixedSupplierCode,(v.vendorSerial||'')+(v.fixedSupplierCode||'')]
      .some(x => masterNorm(x)===masterNorm(code))
  );
  const activeBrands = state.brands.filter(b=>b.active && ['GJ','KD','TT'].includes(b.prefix));
  state.bases = [];
  state.items = [];
  state.priceLists = [];
  for(const row of FINAL_BASE_ITEMS){
    const vendor=vendorFor(row.vendorCode);
    // The first Item Master sheet is authoritative even where supplier is blank.
    // Unassigned bases remain visible but are not eligible for a PO until a supplier is mapped.
    const template = state.plmTemplates.find(t=>t.active!==false && String(t.category).toUpperCase()===row.category)
      || state.plmTemplates.find(t=>t.active!==false && t.category==='*');
    const baseId='base-'+row.baseItemCode.toLowerCase().replace(/[^a-z0-9]+/g,'-');
    state.bases.push({
      id:baseId,code:row.baseItemCode,baseItemCode:row.baseItemCode,productName:row.name,
      description:row.description,category:row.category,family:row.classification||row.category,
      grade:row.grade,engine:row.engine,vendorId:vendor?.id||null,scope:'LAE_IMPORT',
      productionDays:row.productionDays,productionDaysIsReference:true,
      templateId:template?.id||'tpl-generic-lae',previousBaseId:null,
      creationReason:'Imported from final ITEM MASTER.xlsx supplied by Farming Hub.',
      lifecycleStatus:'ACTIVE',specifications:[],at:today+'T00:00:00.000Z',
      source:'ITEM MASTER.xlsx · first sheet is the final Base Item Master'
    });
    for(const brand of activeBrands){
      const itemId='erp-'+brand.prefix.toLowerCase()+'-'+row.baseItemCode.toLowerCase().replace(/[^a-z0-9]+/g,'-');
      state.items.push({
        id:itemId,code:`${brand.prefix}-${row.baseItemCode}`,erpItemCode:`${brand.prefix}-${row.baseItemCode}`,
        baseItemCode:row.baseItemCode,name:row.name,description:row.description,category:row.category,
        baseId,vendorCode:vendor?.code||'',brand:brand.name,brandPrefix:brand.prefix,
        grade:row.grade,engine:row.engine,classification:row.classification,
        productionDays:row.productionDays,productionDaysIsReference:true,
        brandDelta:{branding:brand.name,decals:'',packaging:'',labels:'',colourNotes:'',remarks:''},
        brandDeltaStatus:null,artworkNotes:'',artworkRevisions:[],documents:[],
        active:true,status:'ERP_CODE_READY',scope:'LAE_IMPORT',source:'Generated from final Base Item Master'
      });
    }
  }
  for(const p of FINAL_BASE_PRICES){
    const base=state.bases.find(b=>b.code===p.baseItemCode);
    const vendor=vendorFor(p.vendorCode)||state.vendors.find(v=>v.id===base?.vendorId);
    if(!base||!vendor) continue;
    state.priceLists.push({
      id:`price-${p.baseItemCode}-${p.currency}`.toLowerCase(),
      vendorId:vendor.id,baseId:base.id,baseItemCode:base.code,itemId:null,currency:p.currency,
      unitPriceMinor:majorToMinor(p.unitPrice),effectiveDate:today,remarks:'Imported from PRICE LIST MASTER; rows outside the final Base Item Master were ignored.',
      reference:'ITEM MASTER.xlsx / PRICE LIST MASTER',status:'APPROVED',revision:1,
      at:today+'T00:00:00.000Z',by:'System import',source:'User-supplied final price list'
    });
  }
  const routeDefs=[
    ['NINGBO','', 'CHENNAI'],['QINGDAO','', 'CHENNAI'],['SHENZHEN','', 'CHENNAI'],
    ['CHONGQING','NINGBO','CHENNAI'],['CHONGQING','NANSHA','CHENNAI'],['CHONGQING','QINZHOU','CHENNAI'],['CHONGQING','SHEKOU','CHENNAI']
  ];
  state.routes=routeDefs.map(([origin,via,destination],idx)=>({
    id:`route-final-${idx+1}`,name:`${origin}${via?' via '+via:''} → ${destination}`,origin,via,destination,transitDays:1,
    rateRouteKey:[origin,via?'VIA '+via:'',destination,'1X40HC'].filter(Boolean).join('|'),
    source:'Route created from WEEKLY BUY RATE history. Transit days are reference placeholders; manual total planning TAT remains explicit.'
  }));
  state.freightRates = FREIGHT_HISTORY.map((r,idx)=>({
    id:`freight-history-${idx+1}`,batchId:`freight-history-${r.sequence}`,weekCode:r.weekCode,
    sequence:r.sequence,routeKey:[r.origin,r.via?'VIA '+r.via:'',r.destination,r.containerType].filter(Boolean).join('|'),
    origin:r.origin,via:r.via,destination:r.destination,containerType:r.containerType,rateUsd:r.rateUsd,
    agentChargeUsd:r.agentChargeUsd,benchmarkUsd:r.benchmarkUsd,schedule:r.schedule,
    importedAt:today+'T00:00:00.000Z',importedBy:'System import',source:r.source
  }));
  state.freightImports = [{
    id:'freight-history-final',weekCode:'HISTORICAL + LATEST',sourceFileId:null,
    filename:'WEEKLY BUY RATE.xlsx',at:today+'T00:00:00.000Z',by:'System import',
    count:state.freightRates.length,notes:'24 historical rate snapshots retained in workbook order. Agent charge: USD 60 below USD 3,000; USD 120 from USD 3,000 upward.'
  }];
  state.imports = [{
    id:'item-master-final',sourceFileId:null,filename:'ITEM MASTER.xlsx',templateVersion:'Final Base Item Master',
    mappingVersion:'base-item-to-erp-item-v1',at:today+'T00:00:00.000Z',by:'System import',
    count:FINAL_BASE_ITEMS.length,rows:[],notes:'First sheet treated as final Base Item Master. Three ERP Item Codes generated per base item: GJ-, KD-, TT-.'
  }];
  state.complaints = state.complaints || [];
  state.seededEventCount = state.events.length;
  return state;
}
